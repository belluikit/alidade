// edgeKey is an edge without its derivation, which is RESOLVED for all.
type edgeKey struct {
	from, to graph.ID
	kind     graph.EdgeKind
}

// edges adds, for every reference to a function inside a function body,
// a calls edge from the innermost function holding it when the reference
// is followed by "(", or by a turbofish and "(" (#100), and a references
// edge otherwise: the
// function named as a value (ADR 006 rule 9). Once per pair; a function
// that names itself is a call, recursion, and not a reference.
func (x *extractor) edges() error {
	seen := map[edgeKey]bool{}
	for _, rel := range slices.Sorted(maps.Keys(x.docs)) {
		dc := x.docs[rel]
		lines := bytes.Split(dc.text, []byte("\n"))
		for _, o := range dc.d.GetOccurrences() {
			if err := x.reference(dc, lines, o, seen); err != nil {
				return err
			}
		}
	}
	return nil
}

// reference adds the edge one occurrence makes, if it makes one, and
// counts a call site's outcome.
func (x *extractor) reference(dc *doc, lines [][]byte, o *scip.Occurrence, seen map[edgeKey]bool) error {
	sym, start, end, ok := referenceAt(o)
	if !ok {
		return nil
	}
	caller := innermost(x.funcs[dc], start, nil)
	if caller == nil || inUse(lines, start) {
		return nil // outside a body, or a use declaration inside one: it names, it does not call
	}
	call := callShaped(lines, end)
	target, known := x.resolve(sym, dc)
	if target == nil || !isFunc(target.kind) {
		x.unplaced(sym, call, known, target)
		return nil
	}
	kind := graph.KindCalls
	if call {
		x.report.CallSites++
	} else if kind = graph.KindReferences; caller.id == target.id {
		return nil
	}
	k := edgeKey{caller.id, target.id, kind}
	if seen[k] {
		return nil
	}
	seen[k] = true
	if call {
		x.report.Calls++
	} else {
		x.report.References++
	}
	return x.b.AddEdge(graph.Edge{From: k.from, To: k.to, Kind: k.kind, Derivation: graph.Resolved})
}

// referenceAt reads an occurrence that refers to an item, not a local and
// not a definition: its symbol and where it is.
func referenceAt(o *scip.Occurrence) (sym string, start, end pos, ok bool) {
	sym = o.GetSymbol()
	if o.GetSymbolRoles()&int32(scip.SymbolRole_Definition) != 0 || sym == "" || strings.HasPrefix(sym, "local ") {
		return "", pos{}, pos{}, false
	}
	start, end, ok = occRange(o)
	return sym, start, end, ok
}

// unplaced counts a call site that makes no edge: one to a function
// outside the workspace or generated by its build, when the workspace
// defines no such symbol, or one to a symbol several files define, none
// of them the calling one. A reference to an item that is no function
// is no call site.
func (x *extractor) unplaced(sym string, call, known bool, target *def) {
	switch {
	case !call:
	case !known && namesFunc(sym):
		x.report.CallSites++
		if x.external[sym] {
			x.report.CallsGenerated++
		} else {
			x.report.CallsOutside++
		}
	case known && target == nil:
		x.report.CallSites++
		x.report.CallsUnplaced++
	}
}

// resolve finds the declaration a symbol names from a document: the one in
// that document when the symbol has several, which happens only between
// the crate roots of one package (a test and another test, ADR 002 rule
// 16). known is false when the workspace defines no such symbol; a nil
// def with known true is a symbol several files define, none of them
// this one.
func (x *extractor) resolve(sym string, from *doc) (d *def, known bool) {
	ds := x.bySym[sym]
	switch len(ds) {
	case 0:
		return nil, false
	case 1:
		return ds[0], true
	}
	var only *def
	for _, d := range ds {
		if d.doc == from {
			return d, true
		}
		if only != nil && only.id != d.id {
			return nil, true
		}
		only = d
	}
	return only, true
}

// callShaped says whether what follows a reference ending at end is a
// call's argument list: "(" after any spaces, or a turbofish, "::<…>",
// with "(" after it (#100). A turbofish alone names the function as a
// value: tokio's `drop_arc_raw::<W>` in a waker's vtable. The turbofish may
// span lines, and its arguments nest: `f::<Vec<u8>>(x)`, and `->` in
// `f::<fn() -> u8>(g)` closes nothing.
func callShaped(lines [][]byte, end pos) bool {
	if int(end.line) >= len(lines) {
		return false
	}
	line := lines[end.line]
	if int(end.col) > len(line) {
		return false
	}
	rest := bytes.TrimLeft(line[end.col:], " \t")
	if bytes.HasPrefix(rest, []byte("(")) {
		return true
	}
	if !bytes.HasPrefix(rest, []byte("::<")) {
		return false
	}
	depth, prev := 0, byte(0)
	l, i := int(end.line), int(end.col)+len(line[end.col:])-len(rest)+2
	for ; l < len(lines); l, i = l+1, 0 {
		for ; i < len(lines[l]); i++ {
			switch c := lines[l][i]; {
			case c == '<':
				depth++
			case c == '>' && prev != '-':
				if depth--; depth == 0 {
					return nextIsParen(lines, l, i+1)
				}
			}
			prev = lines[l][i]
		}
	}
	return false
}

// nextIsParen says whether the first byte after spaces, from line l at
// column i on, is "(".
func nextIsParen(lines [][]byte, l, i int) bool {
	for ; l < len(lines); l, i = l+1, 0 {
		if rest := bytes.TrimLeft(lines[l][i:], " \t\r"); len(rest) > 0 {
			return rest[0] == '('
		}
	}
	return false
}

// inUse says whether a reference starting at start is inside a use
// declaration's tree, which may span lines (#114): `use crate::codec::{`
// on one line and `parse,` on the next. It walks back from the reference,
// past // comments, over what a use tree holds (names, paths, braces,
// commas, globs and spaces) to the first byte that is none of those, and
// asks whether the run holds the word use. use is a keyword, and the ";"
// ending an earlier use declaration stops the walk, so a use in the run is
// the declaration holding the reference, whatever comes before it: a
// visibility, `pub(in crate::a) use`, or the "{" opening the body.
func inUse(lines [][]byte, start pos) bool {
	in, _ := useAt(lines, start)
	return in
}

// useAt is inUse, and whether the use is public: `pub use`, pub on the
// keyword's line (#116). `pub(crate) use` is not: the walk stops at its
// ")", with nothing before use.
func useAt(lines [][]byte, start pos) (in, public bool) {
	if int(start.line) >= len(lines) {
		return false, false
	}
	for l := int(start.line); l >= 0; l-- {
		line := lines[l]
		if l == int(start.line) {
			line = line[:min(int(start.col), len(line))]
		}
		line = stripComment(line)
		i := len(line) - 1
		for ; i >= 0 && inUseTree(line[i]); i-- {
		}
		if j := useWord(line[i+1:]); j >= 0 {
			return true, pubBefore(line[i+1 : i+1+j])
		}
		if i >= 0 {
			return false, false // the run ends on this line
		}
	}
	return false, false
}

// useWord is where a line's part of the run holds the word use, or -1.
func useWord(s []byte) int {
	for i := 0; ; i += 3 {
		j := bytes.Index(s[i:], []byte("use"))
		if j < 0 {
			return -1
		}
		i += j
		if (i == 0 || !isWord(s[i-1])) && (i+3 == len(s) || !isWord(s[i+3])) {
			return i
		}
	}
}

// pubBefore says whether what comes before use ends with the word pub.
func pubBefore(s []byte) bool {
	t := bytes.TrimRight(s, " \t")
	return bytes.HasSuffix(t, []byte("pub")) && (len(t) == 3 || !isWord(t[len(t)-4]))
}

// isWord says whether a byte can be part of a word, a raw name's "#"
// included: r#use is a name, not the keyword.
func isWord(c byte) bool { return isIdent(c) || c == '#' }

// inUseTree says whether a byte can be part of a use tree: a name (a raw
// one, r#fn, included), "::", braces, a comma, a glob or a space.
func inUseTree(c byte) bool {
	return isIdent(c) || isSpace(c) || c == ':' || c == ',' || c == '{' || c == '}' || c == '*' || c == '#'
}

// isIdent says whether a byte can be part of a name; one past ASCII is
// taken as part of a non-ASCII name.
func isIdent(c byte) bool {
	return c == '_' || '0' <= c && c <= '9' || 'a' <= c && c <= 'z' || 'A' <= c && c <= 'Z' || c >= 0x80
}

func isSpace(c byte) bool { return c == ' ' || c == '\t' || c == '\r' || c == '\n' }

// namesFunc says whether a symbol names a function or a method: its last
// descriptor is one, "name().".
func namesFunc(sym string) bool {
	s, err := scip.ParseSymbol(sym)
	if err != nil {
		return false
	}
	ds := s.GetDescriptors()
	return len(ds) > 0 && ds[len(ds)-1].GetSuffix() == scip.Descriptor_Method
}
