package ts

import (
	"bufio"
	"bytes"
	"path/filepath"
	"regexp"
	"strings"

	"github.com/belluikit/alidade/internal/graph"
)

// A genFile is what a protoc-gen-es output file states about itself: the
// .proto it came from, and its exports, each with the proto declaration
// it was written for.
type genFile struct {
	protoFile string
	exports   []genExport
}

type genExport struct {
	name string
	kind graph.Kind
	line int
	// from is the fully-qualified proto declaration this export was
	// generated from — the "@generated from message|enum|service"
	// marker above it — or "" for the file descriptor export.
	from string
}

var (
	genHeaderRE = regexp.MustCompile(`@generated by protoc-gen-es\b`)
	genFileRE   = regexp.MustCompile(`@generated from file (\S+)`)
	// genFromRE takes the declaration markers and not the field, rpc or
	// enum-value ones ("@generated from enum value: X = 0;").
	genFromRE   = regexp.MustCompile(`@generated from (message|enum|service) ([\w.]+)\s*$`)
	genExportRE = regexp.MustCompile(`^export (const|type|enum) (\w+)\b`)
	// genExtensionRE is the one other top-level marker protoc-gen-es
	// writes. An extension's export is linked to nothing the layer keys,
	// and the marker ends what the previous message's lent the exports
	// after it (#99); field and value markers inside a message do not.
	genExtensionRE = regexp.MustCompile(`@generated from extension\b`)
)

// parseGenerated reads a file's protoc-gen-es markers, or returns nil for
// a file the generator did not write. The header is looked for in the
// first lines only; a hand-written file quoting the marker deeper down is
// not generated.
func parseGenerated(src []byte) *genFile {
	head := src
	if len(head) > 2048 {
		head = head[:2048]
	}
	if !genHeaderRE.Match(head) {
		return nil
	}
	gf := &genFile{}
	if m := genFileRE.FindSubmatch(head); m != nil {
		gf.protoFile = string(m[1])
	}
	from := ""
	sc := bufio.NewScanner(bytes.NewReader(src))
	sc.Buffer(make([]byte, 1<<20), 1<<24)
	for n := 1; sc.Scan(); n++ {
		line := sc.Text()
		if m := genFromRE.FindStringSubmatch(line); m != nil {
			from = m[2]
			continue
		}
		if genExtensionRE.MatchString(line) {
			from = ""
			continue
		}
		m := genExportRE.FindStringSubmatch(line)
		if m == nil {
			continue
		}
		kind := graph.KindConst
		switch m[1] {
		case "type":
			kind = graph.KindType
		case "enum":
			kind = graph.KindEnum
		}
		gf.exports = append(gf.exports, genExport{name: m[2], kind: kind, line: n, from: from})
	}
	return gf
}

// generatedFile emits a generated file's exports, the contains edges,
// and the generates edges from the proto declarations they were written
// for.
func (x *extractor) generatedFile(file graph.ID, rel string, gf *genFile, d *discovery) error {
	if proto := x.protoFor(gf.protoFile, d); proto != "" {
		to, err := x.m.ProtoFileID(proto)
		if err != nil {
			x.skip(proto, err)
		} else if err := x.generates(to, file); err != nil {
			return err
		}
	} else {
		x.report.ProtoUnmatched++
	}
	for _, e := range gf.exports {
		id, err := x.m.TSID(rel, e.name)
		if err != nil {
			continue
		}
		x.report.Exports++
		attrs := map[string]string{}
		if e.from != "" {
			attrs["proto"] = e.from
		}
		if err := x.b.AddNode(graph.Node{ID: id, Kind: e.kind, Name: e.name, Pos: graph.Position{File: rel, Line: e.line},
			Generated: true, Attrs: attrs}); err != nil {
			return err
		}
		if err := x.b.AddEdge(graph.Edge{From: file, To: id, Kind: graph.KindContains, Derivation: graph.Extracted}); err != nil {
			return err
		}
		if e.from == "" {
			continue
		}
		from, err := x.m.ProtoID(e.from)
		if err != nil {
			continue
		}
		if err := x.generates(from, id); err != nil {
			return err
		}
	}
	return nil
}

func (x *extractor) generates(from, to graph.ID) error {
	x.report.Generates++
	return x.b.AddEdge(graph.Edge{From: from, To: to, Kind: graph.KindGenerates, Derivation: graph.Declared,
		Attrs: map[string]string{"via": "protoc-gen-es"}})
}

// protoFor finds the repository's .proto file a generated header names —
// a path relative to the buf module, so a unique suffix match among the
// .proto files under root — and returns it repo-relative, or "" when
// there is no match or more than one.
func (x *extractor) protoFor(header string, d *discovery) string {
	if header == "" {
		return ""
	}
	suffix := filepath.FromSlash("/" + header)
	match := ""
	for _, p := range d.protos {
		if !strings.HasSuffix(p, suffix) {
			continue
		}
		if match != "" {
			return ""
		}
		match = p
	}
	if match == "" {
		return ""
	}
	if _, err := x.m.RelPath(match); err != nil {
		return ""
	}
	rel, _ := x.m.Rel(match)
	return rel
}
