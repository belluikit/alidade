func specs(cs []importClause) []string {
	var out []string
	for _, c := range cs {
		out = append(out, c.kind+" "+c.spec)
	}
	return out
}

// TestScannerReadsCodeOnly pins #99: an import written inside a template
// literal, a string or a comment is not one; and a comment inside a named
// clause hides no name after it.
func TestScannerReadsCodeOnly(t *testing.T) {
	src := []byte("import { real } from \"./real\";\n" +
		"const tpl = `\nimport { fake } from \"./tpl\";\n${import(\"./inside-template\")}\n`;\n" +
		"const s = \"import('./in-string')\";\n" +
		"/*\nimport { gone } from \"./commented\";\n*/\n" +
		"// import { gone2 } from \"./line-comment\";\n" +
		"import {\n  Foo, // the foo\n  Bar,\n} from \"../gen/user_pb\";\n")
	cs := importClauses(src)
	got := specs(cs)
	want := []string{"import-statement ./real", "import-statement ../gen/user_pb"}
	if !slices.Equal(got, want) {
		t.Errorf("clauses = %v, want %v", got, want)
	}
	for _, c := range cs {
		if c.spec == "../gen/user_pb" && !slices.Equal(c.names, []string{"Foo", "Bar"}) {
			t.Errorf("names = %q, want Foo, Bar", c.names)
		}
	}
}

// TestScannerReadsEveryForm pins #99: default with namespace, TypeScript's
// import-equals, and CommonJS require are imports too; a method named
// require is not.
func TestScannerReadsEveryForm(t *testing.T) {
	src := []byte("import Def, * as ns from \"./both\";\n" +
		"import x = require(\"./tsreq\");\n" +
		"const r = require('./req');\n" +
		"const m = loader.require('./method');\n")
	got := specs(importClauses(src))
	want := []string{"import-statement ./both", "require-call ./tsreq", "require-call ./req"}
	if !slices.Equal(got, want) {
		t.Errorf("clauses = %v, want %v", got, want)
	}
}

// TestExtensionMarkerEndsTheMessagesLoan pins #99: an extension's export is
// not generated from the message above it; a message's Schema const, which
// has no marker of its own, still is.
func TestExtensionMarkerEndsTheMessagesLoan(t *testing.T) {
	src := []byte(`// @generated by protoc-gen-es v2.12.0
// @generated from file app/v1/user.proto (package app.v1, syntax proto3)
/**
 * @generated from message app.v1.User
 */
export type User = Message<"app.v1.User"> & {
  /**
   * @generated from field: string name = 1;
   */
  name: string;
};
export const UserSchema: GenMessage<User> = messageDesc(file_app_v1_user, 0);
/**
 * @generated from extension: string my_ext = 50000;
 */
export const my_ext: GenExtension<FieldOptions, string> = extDesc(file_app_v1_user, 0);
`)
	gf := parseGenerated(src)
	from := map[string]string{}
	for _, e := range gf.exports {
		from[e.name] = e.from
	}
	if from["User"] != "app.v1.User" || from["UserSchema"] != "app.v1.User" {
		t.Errorf("User, UserSchema from %q, %q; want app.v1.User", from["User"], from["UserSchema"])
	}
	if from["my_ext"] != "" {
		t.Errorf("my_ext from %q, want nothing", from["my_ext"])
	}
}

// TestAppsKeepTheirOwnAliases pins #99: in a repository with two SvelteKit
// apps, "$lib" in each resolves into that app; a file of no app does not
// borrow one's aliases; and an import resolving outside the root is
// counted.
func TestAppsKeepTheirOwnAliases(t *testing.T) {
	dir := writeTree(t, map[string]string{
		"appA/svelte.config.js":        "export default { kit: {} };\n",
		"appA/src/lib/util.ts":         "export const a = 1;\n",
		"appA/src/routes/+page.svelte": "<script>\nimport { a } from '$lib/util';\n</script>\n",
		"appB/svelte.config.js":        "export default { kit: {} };\n",
		"appB/src/lib/util.ts":         "export const b = 1;\n",
		"appB/src/routes/+page.svelte": "<script>\nimport { b } from '$lib/util';\n</script>\n",
		"tools/x.ts":                   "import { a } from '$lib/util';\nimport { o } from '../../outside';\n",
		"../outside.ts":                "export const o = 1;\n",
	})
	b := graph.NewBuilder(dir)
	rep, err := Extract(b, dir, DefaultOptions())
	if err != nil {
		t.Fatal(err)
	}
	g := b.Build()
	for page, want := range map[graph.ID]graph.ID{
		"ts://appA/src/routes/+page.svelte": "ts://appA/src/lib/util.ts",
		"ts://appB/src/routes/+page.svelte": "ts://appB/src/lib/util.ts",
	} {
		var to []graph.ID
		for _, e := range g.Out(page) {
			if e.Kind == graph.KindImports {
				to = append(to, e.To)
			}
		}
		if !slices.Equal(to, []graph.ID{want}) {
			t.Errorf("%s imports %v, want %s", page, to, want)
		}
	}
	// A file of no app has no "$lib": esbuild reads it as a package name.
	for _, e := range g.Out("ts://tools/x.ts") {
		if e.Kind == graph.KindImports && e.To != "ts://@pkg/$lib" {
			t.Errorf("tools/x.ts, in no app, imports %s", e.To)
		}
	}
	if rep.Outside != 1 {
		t.Errorf("Outside = %d, want 1", rep.Outside)
	}
}

// writeTree writes files under a temporary root and returns it as the
// build hands it over, symbolic links resolved: a macOS temporary
// directory is one. A name may climb out of the root with "../".
func writeTree(t *testing.T, files map[string]string) string {
	t.Helper()
	dir, err := filepath.EvalSymlinks(t.TempDir())
	if err != nil {
		t.Fatal(err)
	}
	dir = filepath.Join(dir, "repo")
	for name, body := range files {
		if err := writeFile(filepath.Join(dir, name), body); err != nil {
			t.Fatal(err)
		}
	}
	return dir
}

// TestModuleExtensions pins #115: .mjs, .cjs, .mts and .cts are modules of
// the layer, with their imports; their declaration files are not, and a
// build's out/ directory is skipped.
func TestModuleExtensions(t *testing.T) {
	dir := writeTree(t, map[string]string{
		"scripts/gen-config.mjs": "import { cfg } from '../src/config.ts';\nexport default cfg;\n",
		"scripts/legacy.cjs":     "const c = require('../src/config.ts');\n",
		"src/config.ts":          "export const cfg = {};\n",
		"src/util.mts":           "export const u = 1;\n",
		"src/util.d.mts":         "export declare const u: number;\n",
		"out/preload/index.cjs":  "require('../../src/config.ts');\n",
	})
	b := graph.NewBuilder(dir)
	if _, err := Extract(b, dir, DefaultOptions()); err != nil {
		t.Fatal(err)
	}
	g := b.Build()
	for _, id := range []graph.ID{"ts://scripts/gen-config.mjs", "ts://scripts/legacy.cjs", "ts://src/util.mts"} {
		if _, ok := g.Node(id); !ok {
			t.Errorf("missing %s", id)
		}
	}
	for _, id := range []graph.ID{"ts://src/util.d.mts", "ts://out/preload/index.cjs"} {
		if _, ok := g.Node(id); ok {
			t.Errorf("%s is a node", id)
		}
	}
	for _, from := range []graph.ID{"ts://scripts/gen-config.mjs", "ts://scripts/legacy.cjs"} {
		found := false
		for _, e := range g.Out(from) {
			found = found || e.Kind == graph.KindImports && e.To == "ts://src/config.ts"
		}
		if !found {
			t.Errorf("%s does not import src/config.ts", from)
		}
	}
}
