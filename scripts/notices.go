//go:build ignore

// notices writes THIRD_PARTY_NOTICES.txt: the license and notice files of
// everything a release binary of alidade carries (#282).
//
//	go run scripts/notices.go          # write it
//	go run scripts/notices.go -check   # fail when it is out of date
//
// That is Go's own (the standard library and runtime), every module the
// binary links for each release target with the v8 and python tags, the
// libraries CPython is built with (from pylib, for the same targets), the
// jedi tarball's packages, and the Svelte converter's bundle. Go's license
// is read from the toolchain running this, which must be one from go.dev:
// some packagers leave the file out.
package main

import (
	"archive/tar"
	"bytes"
	"compress/gzip"
	"flag"
	"fmt"
	"io"
	"os"
	"os/exec"
	"path"
	"path/filepath"
	"slices"
	"strings"
)

// targets are the release's (scripts/release-build.sh).
var targets = []string{"darwin/arm64", "darwin/amd64", "linux/amd64", "linux/arm64"}

const out = "THIRD_PARTY_NOTICES.txt"

func main() {
	check := flag.Bool("check", false, "fail when "+out+" is out of date, writing nothing")
	flag.Parse()
	text, missing, err := notices()
	if err != nil {
		fmt.Fprintln(os.Stderr, "notices:", err)
		os.Exit(1)
	}
	// A module the binary links with no license file is not one a release
	// can carry: move it to a version that has one.
	for _, m := range missing {
		fmt.Fprintf(os.Stderr, "notices: %s has no license file\n", m)
	}
	if len(missing) > 0 {
		os.Exit(1)
	}
	if *check {
		have, err := os.ReadFile(out)
		if err != nil || !bytes.Equal(have, text) {
			fmt.Fprintf(os.Stderr, "notices: %s is out of date: run go run scripts/notices.go\n", out)
			os.Exit(1)
		}
		return
	}
	if err := os.WriteFile(out, text, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "notices:", err)
		os.Exit(1)
	}
}

// A module is one the binary links, at the version it links.
type module struct{ path, version, dir string }

func notices() ([]byte, []string, error) {
	var b bytes.Buffer
	b.WriteString("alidade's release binaries carry the software below. Each part keeps its\n" +
		"own license, given here in full. Generated by `go run scripts/notices.go`.\n")
	goroot, err := goEnv("GOROOT")
	if err != nil {
		return nil, nil, err
	}
	section(&b, "Go, the standard library and runtime")
	if err := files(&b, goroot, []string{"LICENSE", "PATENTS"}); err != nil {
		return nil, nil, fmt.Errorf("Go's license, from %s: %w", goroot, err)
	}
	mods, err := modules()
	if err != nil {
		return nil, nil, err
	}
	var missing []string
	var pylib string
	for _, m := range mods {
		section(&b, strings.TrimSpace(m.path+" "+m.version))
		names, err := licenseFiles(m.dir)
		if err != nil {
			return nil, nil, err
		}
		if len(names) == 0 {
			missing = append(missing, strings.TrimSpace(m.path+" "+m.version))
		}
		if err := files(&b, m.dir, names); err != nil {
			return nil, nil, err
		}
		if m.path == "github.com/trendvidia/pylib" {
			pylib = m.dir
		}
	}
	if pylib == "" {
		return nil, nil, fmt.Errorf("the binary links no github.com/trendvidia/pylib")
	}
	if err := cpython(&b, pylib); err != nil {
		return nil, nil, err
	}
	if err := jedi(&b); err != nil {
		return nil, nil, err
	}
	section(&b, "The Svelte converter's bundle (internal/adapter/ts/svelte)")
	if err := files(&b, "internal/adapter/ts/svelte", []string{"LICENSES.txt"}); err != nil {
		return nil, nil, err
	}
	return b.Bytes(), missing, nil
}

// modules are the modules the binary links for any release target, but
// alidade's own, sorted by path.
func modules() ([]module, error) {
	seen := map[string]module{}
	for _, t := range targets {
		os_, arch, _ := strings.Cut(t, "/")
		cmd := exec.Command("go", "list", "-deps", "-tags", "v8,python",
			"-f", "{{with .Module}}{{.Path}}\t{{.Version}}\t{{if .Replace}}{{.Replace.Dir}}{{else}}{{.Dir}}{{end}}{{end}}", "./cmd/alidade")
		cmd.Env = append(os.Environ(), "GOOS="+os_, "GOARCH="+arch, "CGO_ENABLED=1")
		cmd.Stderr = os.Stderr
		raw, err := cmd.Output()
		if err != nil {
			return nil, fmt.Errorf("go list for %s: %w", t, err)
		}
		for _, line := range strings.Split(string(raw), "\n") {
			f := strings.Split(line, "\t")
			// The shim is alidade's own code, under typescript-go's path.
			if len(f) != 3 || f[0] == "github.com/belluikit/alidade" || f[0] == "github.com/microsoft/typescript-go/shim" {
				continue
			}
			seen[f[0]] = module{path: f[0], version: f[1], dir: f[2]}
		}
	}
	var mods []module
	for _, m := range seen {
		mods = append(mods, m)
	}
	slices.SortFunc(mods, func(a, b module) int { return strings.Compare(a.path, b.path) })
	return mods, nil
}

// licenseFiles are a directory's license and notice files, sorted.
func licenseFiles(dir string) ([]string, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}
	var names []string
	for _, e := range entries {
		if !e.IsDir() && isLicense(e.Name()) {
			names = append(names, e.Name())
		}
	}
	return names, nil
}

func isLicense(name string) bool {
	name = strings.ToUpper(name)
	for _, p := range []string{"LICENSE", "LICENCE", "COPYING", "NOTICE", "PATENTS"} {
		if strings.HasPrefix(name, p) {
			return true
		}
	}
	return false
}

// cpython adds the licenses pylib carries for CPython and the libraries
// it is built with, once each: the targets' copies are the same files.
func cpython(b *bytes.Buffer, pylib string) error {
	byName := map[string][]byte{}
	for _, t := range targets {
		dir := filepath.Join(pylib, "deps", strings.ReplaceAll(t, "/", "_"), "licenses")
		entries, err := os.ReadDir(dir)
		if err != nil {
			return fmt.Errorf("CPython's licenses for %s: %w", t, err)
		}
		for _, e := range entries {
			text, err := os.ReadFile(filepath.Join(dir, e.Name()))
			if err != nil {
				return err
			}
			if have, ok := byName[e.Name()]; ok && !bytes.Equal(have, text) {
				return fmt.Errorf("pylib's %s differs between targets", e.Name())
			}
			byName[e.Name()] = text
		}
	}
	section(b, "CPython and the libraries it is built with (github.com/trendvidia/pylib)")
	for _, name := range sortedKeys(byName) {
		entry(b, name, byName[name])
	}
	return nil
}

// jedi adds the license files inside the jedi tarball the binary embeds.
func jedi(b *bytes.Buffer) error {
	f, err := os.Open("internal/python/jedi.tar.gz")
	if err != nil {
		return err
	}
	defer f.Close()
	gz, err := gzip.NewReader(f)
	if err != nil {
		return err
	}
	byName := map[string][]byte{}
	tr := tar.NewReader(gz)
	for {
		h, err := tr.Next()
		if err == io.EOF {
			break
		}
		if err != nil {
			return err
		}
		if h.Typeflag == tar.TypeReg && (isLicense(path.Base(h.Name)) || strings.HasPrefix(path.Base(h.Name), "AUTHORS")) {
			text, err := io.ReadAll(tr)
			if err != nil {
				return err
			}
			byName[h.Name] = text
		}
	}
	section(b, "jedi, parso, typeshed and django-stubs (internal/python/jedi.tar.gz)")
	for _, name := range sortedKeys(byName) {
		entry(b, name, byName[name])
	}
	return nil
}

func section(b *bytes.Buffer, title string) {
	fmt.Fprintf(b, "\n%s\n%s\n", strings.Repeat("=", 78), title)
}

func files(b *bytes.Buffer, dir string, names []string) error {
	for _, name := range names {
		text, err := os.ReadFile(filepath.Join(dir, name))
		if err != nil {
			return err
		}
		entry(b, name, text)
	}
	return nil
}

func entry(b *bytes.Buffer, name string, text []byte) {
	fmt.Fprintf(b, "\n--- %s\n\n%s\n", name, bytes.TrimSpace(text))
}

func goEnv(key string) (string, error) {
	raw, err := exec.Command("go", "env", key).Output()
	return strings.TrimSpace(string(raw)), err
}

func sortedKeys[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	slices.Sort(keys)
	return keys
}
